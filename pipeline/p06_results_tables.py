"""
=============================================================================
STEP p06  --  render the definition grid's RESULTS TABLES as markdown.
=============================================================================
Generated from the _comparison tables, never hand-typed, so the numbers in the
write-up cannot drift from the numbers in the outputs. Re-run this after any
re-run of the grid.

Writes <ST>/grid/_comparison/RESULTS_TABLES_DEFINITION_GRID.md containing:
  1. the definition register (what each Def number is)
  2. headline results per definition x window
  3. the marginal effect of each axis
  4. seasonality per definition
  5. day-level agreement highlights
  6. county-rank stability highlights

Reporting conventions enforced here (the project is strict about these):
  * terms are heatwave day / heatwave event / event duration -- never "event-day"
  * per-county MEDIAN and RANGE are the headline; pooled cross-county totals are
    labelled QA-only wherever they appear
  * event duration is reported as median and max, never as a pooled average
=============================================================================
"""
import os, sys
import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import config as C

WINDOW_ORDER = ["w05", "w15", "month", "month_pm7"]
PRIMARY_WINDOW = "w15"


def log(*a):
    print(*a, flush=True)


def md_table(df, cols=None, align=None):
    """Render a DataFrame as a GitHub-flavoured markdown table."""
    d = df[cols] if cols else df
    head = "| " + " | ".join(str(c) for c in d.columns) + " |"
    if align is None:
        align = ["---"] * len(d.columns)
    sep = "| " + " | ".join(align) + " |"
    rows = []
    for _, r in d.iterrows():
        vals = []
        for v in r:
            if isinstance(v, float):
                vals.append("%.0f" % v if float(v).is_integer() else "%.3f" % v)
            else:
                vals.append(str(v))
        rows.append("| " + " | ".join(vals) + " |")
    return "\n".join([head, sep] + rows)


def fmt_int(x):
    try:
        return "{:,}".format(int(x))
    except Exception:
        return str(x)


def build(state):
    cdir = C.comparison_dir(state, make=False)
    tdir = os.path.join(cdir, "tables")
    sname = C.STATE_NAME.get(state, state)

    def read(name, **kw):
        p = os.path.join(tdir, name)
        return pd.read_csv(p, **kw) if os.path.exists(p) else None

    master = read("master_run_summary.csv")
    if master is None:
        log("no master_run_summary.csv -- run run_grid.py then p05 first.")
        return None
    seas = read("seasonality_by_run.csv")
    msum = read("marginal_effects_summary.csv")
    mdet = read("marginal_effects.csv")
    pairs = read("agreement_jaccard_pairs.csv")
    rank = read("county_rank_stability.csv", index_col=0)

    out = []
    A = out.append

    A("# Definition grid — results tables (%s)" % sname)
    A("")
    A("Auto-generated by `pipeline/p06_results_tables.py` from the tables in")
    A("`outputs/%s/grid/_comparison/tables/`. Do not hand-edit: re-run the script." % state)
    A("")
    A("**Grid.** %d definitions × %d threshold windows = **%d runs**, all %s counties, "
      "%d–%d." % (len(C.GRID_DEFINITIONS), len(C.GRID_WINDOWS), len(master),
                  master["counties_total"].max(), C.ANALYSIS_YEARS[0], C.ANALYSIS_YEARS[1]))
    A("")
    A("**Held fixed across every run** (so any difference is attributable to metric, "
      "percentile, duration or window and nothing else): county-relative percentile, "
      "strict `>` comparison, walk-forward baseline (year Y judged against %d…Y−1), "
      "year-round season, no absolute floor, IDW-gap-filled temperature."
      % C.BASELINE_START)
    A("")
    A("**Reporting convention.** *Heatwave day* = one county on one date inside a "
      "qualifying run; *heatwave event* = one uninterrupted run in one county; "
      "*event duration* = integer consecutive dates. Per-county **median and range** are "
      "the substantive results; cross-county pooled totals are marked **QA** and are not "
      "headline quantities. Event duration is reported as median and max — never as a "
      "pooled average.")
    A("")

    # ---------------------------------------------------------------- 1. register
    A("## 1. Definition register")
    A("")
    reg = pd.DataFrame(C.grid_definitions_expanded())
    reg["definition"] = reg.apply(
        lambda r: "county-relative %s > %dth pctl, ≥%d consecutive days"
        % (r["metric_label"], r["percentile"], r["min_duration"]), axis=1)
    reg = reg.sort_values("def_number")
    reg["Def"] = reg["def_number"].map(lambda x: "Def %02d" % x)
    reg["item"] = reg["user_item"]
    A(md_table(reg, ["Def", "item", "definition_id", "definition"]))
    A("")
    A("`item` is the item number in the request that specified this round. "
      "Def 01 (`MHI_P85_2D`) and Def 02 (`MHI_P95_2D`) were completed earlier and are "
      "not re-run here; their published outputs are in `outputs/%s/def_p85_2d` and "
      "`def_p95_2d`." % state)
    A("")

    # ---------------------------------------------------------------- 2. headline
    A("## 2. Headline results per definition × window")
    A("")
    A("Per-county heatwave days over %d–%d. `median (min–max)` across counties; "
      "`dur` = event duration median/max in days; `QA days` and `QA events` are the "
      "cross-county pooled totals (QA only)." % C.ANALYSIS_YEARS)
    A("")
    m = master.copy()
    m["Def"] = m["def_number"].map(lambda x: "Def %02d" % x)
    m["per-county days median (min–max)"] = m.apply(
        lambda r: "%s (%s–%s)" % (fmt_int(r["per_county_heatwave_days_median"]),
                                  fmt_int(r["per_county_heatwave_days_min"]),
                                  fmt_int(r["per_county_heatwave_days_max"])), axis=1)
    m["dur med/max"] = m.apply(lambda r: "%s / %s" % (fmt_int(r["event_duration_median_days"]),
                                                      fmt_int(r["event_duration_max_days"])), axis=1)
    m["QA days"] = m["heatwave_days_QA_pooled"].map(fmt_int)
    m["QA events"] = m["heatwave_events_QA_pooled"].map(fmt_int)
    m["Jun–Sep %"] = m["pct_heatwave_days_jun_sep"].map(lambda v: "%.0f%%" % v)
    m["window"] = m["window_key"]
    m = m.sort_values(["def_number", "window_order"])
    A(md_table(m, ["Def", "definition_id", "window", "per-county days median (min–max)",
                   "dur med/max", "Jun–Sep %", "QA days", "QA events"]))
    A("")

    # primary-window-only compact view
    A("### Primary window (`%s`) only" % PRIMARY_WINDOW)
    A("")
    p = m[m["window_key"] == PRIMARY_WINDOW].sort_values(
        "per_county_heatwave_days_median", ascending=False)
    A(md_table(p, ["Def", "definition_id", "per-county days median (min–max)",
                   "dur med/max", "Jun–Sep %", "QA days", "QA events"]))
    A("")

    # ---------------------------------------------------------------- 3. marginal
    if msum is not None and len(msum):
        A("## 3. Marginal effect of each definition choice")
        A("")
        A("Matched pairs: two runs identical on the other three axes, so each row "
          "isolates one axis. **Jaccard** is day-level agreement on the set of "
          "(county, date) heatwave days — lower means the axis changes *which days* get "
          "flagged more. **Days ratio** is the pooled heatwave-day count of the higher "
          "run over the lower.")
        A("")
        s = msum.copy()
        s["axis"] = s["axis"].str.capitalize()
        s["Jaccard median (min–max)"] = s.apply(
            lambda r: "%.3f (%.3f–%.3f)" % (r["jaccard_median"], r["jaccard_min"],
                                            r["jaccard_max"]), axis=1)
        s["Days ratio median (min–max)"] = s.apply(
            lambda r: "%.2f× (%.2f–%.2f)" % (r["days_ratio_median"], r["days_ratio_min"],
                                             r["days_ratio_max"]), axis=1)
        s["pairs"] = s["n_matched_pairs"]
        A(md_table(s.sort_values("jaccard_median"),
                   ["axis", "pairs", "Jaccard median (min–max)", "Days ratio median (min–max)"]))
        A("")
        A("Yardsticks from this project's earlier sensitivity work, for reading those "
          "Jaccard values: **walk-forward vs fixed baseline = 0.923**; "
          "**anchor-station vs multi-station composite temperature = 0.45–0.73**. "
          "An axis that scores below ~0.73 changes the classification more than "
          "switching the temperature data source did.")
        A("")

        if mdet is not None and len(mdet):
            A("### Every single-axis contrast")
            A("")
            for axis in ["metric", "percentile", "duration", "window"]:
                d = mdet[mdet["axis"] == axis]
                if not len(d):
                    continue
                A("**%s**" % axis.capitalize())
                A("")
                dd = d.copy()
                dd["contrast"] = (dd["contrast_pair"] if "contrast_pair" in dd.columns
                                  else dd["from_value"].astype(str) + " vs " + dd["to_value"].astype(str))
                agg = (dd.groupby("contrast")
                       .agg(pairs=("jaccard", "size"), jaccard_median=("jaccard", "median"),
                            ratio_median=("days_ratio_hi_over_lo", "median"))
                       .reset_index().sort_values("jaccard_median"))
                agg["Jaccard median"] = agg["jaccard_median"].map(lambda v: "%.3f" % v)
                agg["Days ratio median"] = agg["ratio_median"].map(lambda v: "%.2f×" % v)
                A(md_table(agg, ["contrast", "pairs", "Jaccard median", "Days ratio median"]))
                A("")

    # ---------------------------------------------------------------- 4. seasonality
    if seas is not None and len(seas):
        A("## 4. Seasonality")
        A("")
        A("A year-round *relative* definition flags days that are unusual **for the date**, "
          "so cool-season days can qualify. This table is how much of each definition's "
          "heatwave-day count falls in the warm season.")
        A("")
        sp = seas[seas["window_key"] == PRIMARY_WINDOW].copy()
        sp = sp.merge(master[["run_id", "def_number"]], on="run_id", how="left")
        sp["Def"] = sp["def_number"].map(lambda x: "Def %02d" % x)
        sp["Jun–Sep %"] = sp["pct_jun_sep"].map(lambda v: "%.0f%%" % v)
        sp["outside Jun–Sep %"] = sp["pct_outside_jun_sep"].map(lambda v: "%.0f%%" % v)
        sp["peak month"] = sp["peak_month"]
        A(md_table(sp.sort_values("pct_jun_sep", ascending=False),
                   ["Def", "definition_id", "Jun–Sep %", "outside Jun–Sep %", "peak month"]))
        A("")
        A("Full monthly breakdown: `tables/seasonality_by_run.csv`.")
        A("")

    # ---------------------------------------------------------------- 5. agreement
    if pairs is not None and len(pairs):
        A("## 5. Day-level agreement highlights")
        A("")
        one = pairs[pairs["n_axes_differing"] == 1]
        A("- Pairwise comparisons: **%s** across %d runs; **%s** differ on exactly one axis."
          % (fmt_int(len(pairs)), len(master), fmt_int(len(one))))
        A("- Overall Jaccard range: **%.3f – %.3f** (median %.3f)."
          % (pairs["jaccard"].min(), pairs["jaccard"].max(), pairs["jaccard"].median()))
        A("")
        A("**Most similar definition pairs** (highest day-level agreement):")
        A("")
        top = pairs.nlargest(10, "jaccard")[["run_a", "run_b", "jaccard", "axes_differing"]]
        A(md_table(top))
        A("")
        A("**Least similar definition pairs** (lowest day-level agreement):")
        A("")
        bot = pairs.nsmallest(10, "jaccard")[["run_a", "run_b", "jaccard", "axes_differing"]]
        A(md_table(bot))
        A("")

    # ---------------------------------------------------------------- 6. rank stability
    if rank is not None and len(rank):
        A("## 6. County-rank stability")
        A("")
        vals = rank.to_numpy().astype(float)
        iu = np.triu_indices_from(vals, k=1)
        off = vals[iu]
        A("Spearman correlation of per-county heatwave-day totals between runs "
          "(%d run pairs): **median %.3f**, range **%.3f – %.3f**."
          % (len(off), float(np.nanmedian(off)), float(np.nanmin(off)), float(np.nanmax(off))))
        A("")
        A("High rank correlation alongside low day-level agreement would mean the "
          "definitions disagree about *which days* are heatwave days while still ranking "
          "counties similarly. Full matrix: `tables/county_rank_stability.csv`.")
        A("")

    # ---------------------------------------------------------------- files
    A("## Files")
    A("")
    A("```")
    A("outputs/%s/grid/" % state)
    A("  <DEFINITION_ID>/tables/    heatwave_events_<w>.csv.gz, county_year_summary_<w>.csv,")
    A("                             county_month_summary_<w>.csv, state_year_qc_<w>.csv,")
    A("                             run_summary_<w>.json, daily_heatwave_days_<w>.csv.gz*")
    A("  <DEFINITION_ID>/figures/   map01, map02, dist01, seas01, map05 (per window)")
    A("                             + cmpwin01 window sensitivity (per definition)")
    A("  _comparison/tables/        master_run_summary.csv, master_county_run_summary.csv,")
    A("                             agreement_jaccard_matrix.csv, agreement_jaccard_pairs.csv,")
    A("                             marginal_effects.csv, marginal_effects_summary.csv,")
    A("                             county_rank_stability.csv, seasonality_by_run.csv")
    A("  _comparison/figures/       cmp01 jaccard, cmp02 marginal effects, cmp03 days by")
    A("                             definition, cmp04 seasonality, cmp05 window effect,")
    A("                             cmp06 rank stability")
    A("  _thresholds/*              shared threshold cache (metric x percentile x window)")
    A("  run_log.csv                provenance: git commit + input hash per run")
    A("```")
    A("")
    A("`*` git-ignored (large, fully regenerable).")
    A("")
    A("Registry of every run and its status: `pipeline/definition_registry.csv`.")

    text = "\n".join(out) + "\n"
    path = os.path.join(cdir, "RESULTS_TABLES_DEFINITION_GRID.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    log("[p06] wrote %s (%d lines)" % (path, len(out)))
    return path


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--state", action="append", default=None)
    a = ap.parse_args()
    for st in (a.state or C.STATES):
        build(st)
